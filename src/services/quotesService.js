/**
 * Returns categories corresponding to the chosen language.
 */
export function getCategories(language = 'id') {
  if (language === 'id') return INDONESIAN_CATEGORIES;
  if (language === 'en') return ENGLISH_CATEGORIES;
  // For 'random', return all unique categories
  return ['ALL', ...new Set([...INDONESIAN_CATEGORIES.slice(1), ...ENGLISH_CATEGORIES.slice(1)])];
}

/**
 * Generates a random quote based on category, language, and avoids repeating the previous quote.
 * @param {string} selectedCategory 
 * @param {'id' | 'en' | 'random'} language 
 * @param {string} previousQuote - The quote text to avoid repeating consecutively
 */
export function getRandomQuote(selectedCategory = 'ALL', language = 'id', previousQuote = '') {
  let targetLang = language;
  if (targetLang === 'random') {
    targetLang = Math.random() < 0.5 ? 'id' : 'en';
  }

  let pool = targetLang === 'en' ? ENGLISH_QUOTES : INDONESIAN_QUOTES;

  // Filter by category if selected and not ALL
  if (selectedCategory && selectedCategory !== 'ALL') {
    const filtered = pool.filter(q => q.category.toLowerCase() === selectedCategory.toLowerCase());
    if (filtered.length > 0) {
      pool = filtered;
    }
  }

  // Prevent consecutive duplicate if pool has more than 1 quote
  if (pool.length > 1 && previousQuote) {
    const trimmedPrev = previousQuote.trim().toLowerCase();
    const nonDuplicatePool = pool.filter(q => q.quote.trim().toLowerCase() !== trimmedPrev);
    if (nonDuplicatePool.length > 0) {
      pool = nonDuplicatePool;
    }
  }

  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}

